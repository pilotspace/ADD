#!/usr/bin/env python3
"""campaign.py — aggregate repetition-set run trees into one committed campaign record (W6).

The amb1 campaign's means were computed by hand in a scratch shell; that works exactly once.
This makes the aggregation a program so a committed record is reproducible from its run trees
by anyone:

    python3 -m benchmark.campaign <runs-root> [<runs-root>...] [--out CAMPAIGN.md]

Every `record.json` under the given roots is collected (rep dirs nest freely), grouped by
arm. Only `status: done` records count — a half-run is not a data point — and every skipped
record is NAMED in the output, because a silent skip is the meter lying about its own
coverage. Output is deterministic (sorted arms, sorted item ids): a campaign record that
diffs against itself on re-run is not a record.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys


def _stats(vals: list[float]) -> dict:
    return {"n": len(vals), "mean": sum(vals) / len(vals), "min": min(vals), "max": max(vals)}


def aggregate(roots) -> dict:
    """`{arms: {name: {reps, items, metrics, safe_rate}}, skipped: [...]}` over run trees."""
    arms: dict = {}
    skipped: list[str] = []
    found = 0
    for root in roots:
        for path in sorted(pathlib.Path(root).rglob("record.json")):
            found += 1
            try:
                rec = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as err:
                skipped.append(f"{path} (unreadable: {err})")
                continue
            if rec.get("status") != "done":
                skipped.append(f"{path} (status: {rec.get('status')!r})")
                continue
            arm = arms.setdefault(str(rec.get("arm", "?")),
                                  {"reps": 0, "items": {}, "_metrics": {}, "_safe": []})
            arm["reps"] += 1
            detail = (rec.get("artifacts") or {}).get("ambiguity_detail")
            items = json.loads(detail) if isinstance(detail, str) and detail else (detail or [])
            safe = 0
            for item in items:
                tally = arm["items"].setdefault(str(item.get("id")), {})
                verdict = str(item.get("verdict"))
                tally[verdict] = tally.get(verdict, 0) + 1
                safe += verdict in ("surfaced", "guessed_right")
            if items:
                arm["_safe"].append(safe / len(items))
            for key, val in (rec.get("metrics") or {}).items():
                if isinstance(val, (int, float)):
                    arm["_metrics"].setdefault(key, []).append(float(val))
    if not found:
        raise ValueError(f"no record.json under {[str(r) for r in roots]} — nothing to aggregate")
    if not arms:
        raise ValueError("records found, but none with status `done` — nothing to aggregate")
    return {
        "arms": {name: {
            "reps": arm["reps"],
            "items": {i: dict(sorted(t.items())) for i, t in sorted(arm["items"].items())},
            "metrics": {k: _stats(v) for k, v in sorted(arm["_metrics"].items())},
            "safe_rate": _stats(arm["_safe"]) if arm["_safe"]
                         else {"n": 0, "mean": None, "min": None, "max": None},
        } for name, arm in sorted(arms.items())},
        "skipped": skipped,
    }


def render_markdown(campaign: dict, note: str = None) -> str:
    """The committed view. Deterministic; every number traces to the aggregate.

    `note` is for the caveat a pooled record NEEDS in-band (e.g. "reps span five engine
    versions") — a caveat living only in a commit message is a caveat nobody reads.
    """
    lines = ["# Campaign record", "",
             "Generated by `benchmark/campaign.py` — reproducible from the run trees.", ""]
    if note:
        lines += [f"> {note}", ""]
    for name in sorted(campaign["arms"]):
        arm = campaign["arms"][name]
        sr = arm["safe_rate"]
        lines += [f"## {name} — {arm['reps']} rep(s)", "",
                  f"- safe rate (surfaced + guessed_right): mean {sr['mean']} "
                  f"(n={sr['n']}, min {sr['min']}, max {sr['max']})"]
        for key, s in arm["metrics"].items():
            lines.append(f"- {key}: mean {round(s['mean'], 4)} · min {s['min']} · "
                         f"max {s['max']} · n {s['n']}")
        lines += ["", "| item | verdicts across reps |", "|---|---|"]
        for item, tally in arm["items"].items():
            cells = " · ".join(f"{v} ×{n}" for v, n in tally.items())
            lines.append(f"| {item} | {cells} |")
        lines.append("")
    if campaign["skipped"]:
        lines += ["## Skipped (found, not counted)", ""]
        lines += [f"- {s}" for s in campaign["skipped"]]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="campaign.py")
    parser.add_argument("roots", nargs="+", help="run trees (rep dirs nest freely)")
    parser.add_argument("--out", default=None, help="write the markdown record here")
    parser.add_argument("--note", default=None,
                        help="in-band caveat for the record (e.g. heterogeneous reps)")
    args = parser.parse_args(argv)
    try:
        campaign = aggregate([pathlib.Path(r) for r in args.roots])
    except ValueError as err:
        print(str(err), file=sys.stderr)
        return 2
    text = render_markdown(campaign, note=args.note)
    if args.out:
        pathlib.Path(args.out).write_text(text, encoding="utf-8")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
